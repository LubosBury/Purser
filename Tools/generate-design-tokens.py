#!/usr/bin/env python3
"""Generate App/Shared/Design/PurserTokens.swift from docs/design/tokens.json.

Usage (from the repo root, stdlib only, always with -I):
    python3 -I Tools/generate-design-tokens.py           # write the Swift file
    python3 -I Tools/generate-design-tokens.py --check   # exit 1 if the file is out of date

The Swift file is generated: never edit it by hand. Change the token in the
Purser design system artifact, copy its tokens.json to docs/design/, rerun this.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs/design/tokens.json"
OUT = ROOT / "App/Shared/Design/PurserTokens.swift"

WEIGHTS = {400: ".regular", 500: ".medium", 600: ".semibold", 700: ".bold"}


def camel(name: str) -> str:
    head, *rest = re.split(r"[-_.]", name)
    out = head + "".join(p[:1].upper() + p[1:] for p in rest)
    return "_" + out if out[0].isdigit() else out


def px(value) -> float:
    m = re.fullmatch(r"(-?\d+(?:\.\d+)?)(px)?", str(value).strip())
    if not m:
        sys.exit(f"unsupported length: {value!r}")
    return float(m.group(1))


def num(x: float) -> str:
    return str(int(x)) if x == int(x) else str(x)


def color_expr(value: str) -> str:
    if value.startswith("{") and value.endswith("}"):
        return "PurserColor." + camel(value[1:-1])
    m = re.fullmatch(r"#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?", value)
    if not m:
        sys.exit(f"unsupported color (hex only): {value!r}")
    rgb = "0x" + m.group(1).upper()
    if m.group(2):
        return f"Color(hex: {rgb}, alpha: {int(m.group(2), 16)} / 255)"
    return f"Color(hex: {rgb})"


def build(tokens: dict) -> str:
    theme = tokens["color"]["themes"][0]["id"]
    lines = [
        "// GENERATED by Tools/generate-design-tokens.py from docs/design/tokens.json. Do not edit.",
        "// Source of truth: the Purser design system artifact. See docs/design/README.md.",
        "// Shadows and blur are not generated: use `.glassEffect` or Material, see docs/design/components/GlassPanel.md.",
        "",
        "import SwiftUI",
        "",
        f"/// Colors of the `{theme}` theme. The app is dark only: set `.preferredColorScheme(.dark)` on the window.",
        "enum PurserColor {",
    ]
    for t in tokens["color"]["tokens"]:
        v = t["value"]
        v = v[theme] if isinstance(v, dict) else v
        lines.append(f"    /// {t['usage']}")
        lines.append(f"    static let {camel(t['name'])} = {color_expr(v)}")
    lines += ["}", "", "enum PurserSpacing {"]
    for t in tokens["spacing"]["tokens"]:
        lines.append(f"    static let {camel(t['name'])}: CGFloat = {num(px(t['value']))}")
    lines += ["}", "", "enum PurserRadius {"]
    for t in tokens["radius"]["tokens"]:
        lines.append(f"    static let {camel(t['name'])}: CGFloat = {num(px(t['value']))}")
    lines += ["}", "", "/// Sizes and weights of the text styles. Line height and tracking are not generated."]
    lines.append("enum PurserFont {")
    for g in tokens["type"]["groups"]:
        mono = g.get("family") == "mono"
        for s in g["styles"]:
            weight = WEIGHTS.get(int(s["fontWeight"]))
            if weight is None:
                sys.exit(f"unsupported weight: {s['fontWeight']!r}")
            design = ", design: .monospaced" if mono else ""
            digits = ".monospacedDigit()" if mono else ""
            lines.append(f"    /// {s.get('usage', '')}".rstrip())
            lines.append(
                f"    static let {camel(s['name'])} = Font.system(size: {num(px(s['fontSize']))}, weight: {weight}{design}){digits}"
            )
    lines += [
        "}",
        "",
        "private extension Color {",
        "    init(hex: UInt32, alpha: Double = 1) {",
        "        self.init(",
        "            .sRGB,",
        "            red: Double((hex >> 16) & 0xFF) / 255,",
        "            green: Double((hex >> 8) & 0xFF) / 255,",
        "            blue: Double(hex & 0xFF) / 255,",
        "            opacity: alpha",
        "        )",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    text = build(json.loads(SRC.read_text()))
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date: run python3 -I Tools/generate-design-tokens.py")
        print("design tokens up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
